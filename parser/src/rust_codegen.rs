//! Rust Code Generator for Sigil
//!
//! Translates Sigil AST to idiomatic Rust source code.
//! This enables Nihil (written in Sigil) to be compiled to Rust crates
//! for use by Infernum and other Rust projects.
//!
//! # Usage
//! ```bash
//! sigil rust program.sg              # Output to stdout
//! sigil rust program.sg -o out.rs    # Output to file
//! ```

use crate::ast::*;
use crate::span::Span;
use std::collections::HashSet;
use std::fmt::Write;

/// Configuration options for Rust code generation.
#[derive(Debug, Clone)]
pub struct RustCodegenOptions {
    /// Preserve evidence wrappers (Known<T>, Uncertain<T>, Reported<T>)
    pub preserve_evidence: bool,
    /// Emit source comments showing original Sigil
    pub emit_comments: bool,
    /// Rust edition to target
    pub edition: RustEdition,
    /// Generate #![no_std] crate
    pub no_std: bool,
    /// Indentation style
    pub indent_spaces: usize,
}

impl Default for RustCodegenOptions {
    fn default() -> Self {
        Self {
            preserve_evidence: false,
            emit_comments: false,
            edition: RustEdition::Edition2021,
            no_std: false,
            indent_spaces: 4,
        }
    }
}

/// Rust edition for output.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum RustEdition {
    Edition2018,
    Edition2021,
    Edition2024,
}

impl RustEdition {
    pub fn as_str(&self) -> &'static str {
        match self {
            RustEdition::Edition2018 => "2018",
            RustEdition::Edition2021 => "2021",
            RustEdition::Edition2024 => "2024",
        }
    }
}

/// Errors during Rust code generation.
#[derive(Debug, Clone)]
pub struct RustCodegenError {
    pub message: String,
    pub span: Option<Span>,
}

impl std::fmt::Display for RustCodegenError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "{}", self.message)
    }
}

impl std::error::Error for RustCodegenError {}

pub type RustCodegenResult<T> = Result<T, RustCodegenError>;

/// The Rust code generator.
pub struct RustCompiler {
    output: String,
    indent: usize,
    imports: HashSet<String>,
    options: RustCodegenOptions,
    /// Track local bindings to determine path separators (. vs ::)
    local_bindings: HashSet<String>,
}

impl RustCompiler {
    pub fn new() -> Self {
        Self::with_options(RustCodegenOptions::default())
    }

    pub fn with_options(options: RustCodegenOptions) -> Self {
        Self {
            output: String::new(),
            indent: 0,
            imports: HashSet::new(),
            options,
            local_bindings: HashSet::new(),
        }
    }

    /// Compile AST items to Rust source code.
    pub fn compile(&mut self, items: &[Item]) -> RustCodegenResult<String> {
        self.output.clear();
        self.imports.clear();
        self.local_bindings.clear();

        // Header
        writeln!(self.output, "// Generated by Sigil Rust Codegen").unwrap();
        writeln!(self.output, "// Edition: {}", self.options.edition.as_str()).unwrap();
        if self.options.no_std {
            writeln!(self.output, "#![no_std]").unwrap();
        }
        self.output.push('\n');

        // Generate code for each item
        for item in items {
            self.emit_item(item)?;
            self.output.push('\n');
        }

        Ok(self.output.clone())
    }

    // Output helpers
    fn write(&mut self, s: &str) { self.output.push_str(s); }
    fn writeln(&mut self, s: &str) { self.write_indent(); self.output.push_str(s); self.output.push('\n'); }
    fn newline(&mut self) { self.output.push('\n'); }
    fn write_indent(&mut self) { for _ in 0..(self.indent * self.options.indent_spaces) { self.output.push(' '); } }
    fn indent(&mut self) { self.indent += 1; }
    fn dedent(&mut self) { if self.indent > 0 { self.indent -= 1; } }

    // Item emission
    fn emit_item(&mut self, item: &Item) -> RustCodegenResult<()> {
        match item {
            Item::Function(f) => self.emit_function(f),
            Item::Struct(s) => self.emit_struct(s),
            Item::Enum(e) => self.emit_enum(e),
            Item::Trait(t) => self.emit_trait(t),
            Item::Impl(i) => self.emit_impl(i),
            Item::ExternBlock(eb) => self.emit_extern_block(eb),
            Item::Const(c) => self.emit_const(c),
            Item::Static(s) => self.emit_static(s),
            Item::TypeAlias(a) => self.emit_type_alias(a),
            Item::Use(u) => self.emit_use(u),
            Item::Module(m) => self.emit_module(m),
            Item::Actor(_) => { self.writeln("// TODO: Actor"); Ok(()) }
            Item::Macro(_) | Item::MacroInvocation(_) => { self.writeln("// TODO: Macro"); Ok(()) }
            Item::Plurality(_) => { self.writeln("// TODO: Plurality"); Ok(()) }
        }
    }

    fn emit_function(&mut self, func: &Function) -> RustCodegenResult<()> {
        // Clear local bindings from previous function
        self.local_bindings.clear();

        // Add function parameters as local bindings
        for param in &func.params {
            let mut bindings = Vec::new();
            self.collect_pattern_bindings(&param.pattern, &mut bindings);
            for name in bindings {
                self.local_bindings.insert(name);
            }
        }

        // Emit function attributes
        self.emit_function_attrs(&func.attrs)?;

        self.write_indent();

        // Handle export attribute: #[export] → pub extern "C"
        if func.attrs.export {
            self.write("pub extern \"C\" ");
        } else {
            self.emit_visibility(&func.visibility);
        }

        if func.is_async { self.write("async "); }
        if func.is_unsafe { self.write("unsafe "); }
        if func.is_const { self.write("const "); }
        self.write("fn ");
        self.write(&func.name.name);

        if let Some(ref g) = func.generics {
            self.emit_generics(g)?;
        }

        self.write("(");
        for (i, param) in func.params.iter().enumerate() {
            if i > 0 { self.write(", "); }
            self.emit_param(param)?;
        }
        self.write(")");

        if let Some(ref ret) = func.return_type {
            self.write(" -> ");
            self.emit_type(ret)?;
        }

        // Emit where clause if present
        if let Some(ref wc) = func.where_clause {
            self.emit_where_clause(wc)?;
        }

        if let Some(ref body) = func.body {
            self.write(" ");
            self.emit_block(body)?;
        } else {
            self.write(";");
        }
        self.newline();
        Ok(())
    }

    fn emit_where_clause(&mut self, wc: &crate::ast::WhereClause) -> RustCodegenResult<()> {
        if wc.predicates.is_empty() {
            return Ok(());
        }
        self.write("\n");
        self.write_indent();
        self.write("where ");
        for (i, pred) in wc.predicates.iter().enumerate() {
            if i > 0 {
                self.write(",\n");
                self.write_indent();
                self.write("      ");
            }
            self.emit_type(&pred.ty)?;
            self.write(": ");
            for (j, bound) in pred.bounds.iter().enumerate() {
                if j > 0 { self.write(" + "); }
                self.emit_type(bound)?;
            }
        }
        Ok(())
    }

    fn emit_struct(&mut self, s: &StructDef) -> RustCodegenResult<()> {
        // Emit outer attributes first (except derive, repr which are handled specially)
        for attr in &s.attrs.outer_attrs {
            // Skip derive and repr - they're handled separately
            if attr.name.name == "derive" || attr.name.name == "repr" {
                continue;
            }
            self.write_indent();
            self.write("#[");
            self.write(&attr.name.name);
            if let Some(args) = &attr.args {
                self.emit_attr_args(args)?;
            }
            self.write("]\n");
        }

        // Emit derives
        if !s.attrs.derives.is_empty() {
            self.write_indent();
            self.write("#[derive(");
            for (i, derive) in s.attrs.derives.iter().enumerate() {
                if i > 0 { self.write(", "); }
                match derive {
                    DeriveTrait::Debug => self.write("Debug"),
                    DeriveTrait::Clone => self.write("Clone"),
                    DeriveTrait::Copy => self.write("Copy"),
                    DeriveTrait::Default => self.write("Default"),
                    DeriveTrait::PartialEq => self.write("PartialEq"),
                    DeriveTrait::Eq => self.write("Eq"),
                    DeriveTrait::PartialOrd => self.write("PartialOrd"),
                    DeriveTrait::Ord => self.write("Ord"),
                    DeriveTrait::Hash => self.write("Hash"),
                    DeriveTrait::Component => self.write("Component"),
                    DeriveTrait::Resource => self.write("Resource"),
                    DeriveTrait::Bundle => self.write("Bundle"),
                    DeriveTrait::Serialize => self.write("serde::Serialize"),
                    DeriveTrait::Deserialize => self.write("serde::Deserialize"),
                    DeriveTrait::Custom(name) => self.write(name),
                }
            }
            self.write(")]\n");
        }

        // Emit repr attributes
        if let Some(ref repr) = s.attrs.repr {
            self.write_indent();
            match repr {
                StructRepr::C => self.write("#[repr(C)]\n"),
                StructRepr::Transparent => self.write("#[repr(transparent)]\n"),
                StructRepr::Int(int_ty) => {
                    self.write("#[repr(");
                    self.write(int_ty);
                    self.write(")]\n");
                }
            }
        }
        if s.attrs.packed {
            self.write_indent();
            self.write("#[repr(packed)]\n");
        }
        if let Some(align) = s.attrs.align {
            self.write_indent();
            self.write("#[repr(align(");
            self.write(&align.to_string());
            self.write("))]\n");
        }

        self.write_indent();
        self.emit_visibility(&s.visibility);
        self.write("struct ");
        self.write(&s.name.name);

        if let Some(ref g) = s.generics {
            self.emit_generics(g)?;
        }

        match &s.fields {
            StructFields::Unit => self.write(";"),
            StructFields::Named(fields) => {
                self.write(" {\n");
                self.indent();
                for field in fields {
                    self.write_indent();
                    self.emit_visibility(&field.visibility);
                    self.write(&field.name.name);
                    self.write(": ");
                    self.emit_type(&field.ty)?;
                    self.write(",\n");
                }
                self.dedent();
                self.write_indent();
                self.write("}");
            }
            StructFields::Tuple(types) => {
                self.write("(");
                for (i, ty) in types.iter().enumerate() {
                    if i > 0 { self.write(", "); }
                    self.emit_type(ty)?;
                }
                self.write(");");
            }
        }
        self.newline();
        Ok(())
    }

    fn emit_enum(&mut self, e: &EnumDef) -> RustCodegenResult<()> {
        // Emit outer attributes (derives, repr, etc.)
        for attr in &e.outer_attrs {
            self.write_indent();
            self.write("#[");
            self.write(&attr.name.name);
            if let Some(args) = &attr.args {
                self.emit_attr_args(args)?;
            }
            self.write("]\n");
        }

        self.write_indent();
        self.emit_visibility(&e.visibility);
        self.write("enum ");
        self.write(&e.name.name);

        if let Some(ref g) = e.generics {
            self.emit_generics(g)?;
        }

        self.write(" {\n");
        self.indent();
        for variant in &e.variants {
            self.write_indent();
            self.write(&variant.name.name);
            match &variant.fields {
                StructFields::Unit => {}
                StructFields::Named(fields) => {
                    self.write(" { ");
                    for (i, f) in fields.iter().enumerate() {
                        if i > 0 { self.write(", "); }
                        self.write(&f.name.name);
                        self.write(": ");
                        self.emit_type(&f.ty)?;
                    }
                    self.write(" }");
                }
                StructFields::Tuple(types) => {
                    self.write("(");
                    for (i, ty) in types.iter().enumerate() {
                        if i > 0 { self.write(", "); }
                        self.emit_type(ty)?;
                    }
                    self.write(")");
                }
            }
            if let Some(ref d) = variant.discriminant {
                self.write(" = ");
                self.emit_expr(d)?;
            }
            self.write(",\n");
        }
        self.dedent();
        self.write_indent();
        self.write("}");
        self.newline();
        Ok(())
    }

    fn emit_trait(&mut self, t: &TraitDef) -> RustCodegenResult<()> {
        self.write_indent();
        self.emit_visibility(&t.visibility);
        self.write("trait ");
        self.write(&t.name.name);

        if let Some(ref g) = t.generics {
            self.emit_generics(g)?;
        }

        if !t.supertraits.is_empty() {
            self.write(": ");
            for (i, bound) in t.supertraits.iter().enumerate() {
                if i > 0 { self.write(" + "); }
                self.emit_type(bound)?;
            }
        }

        self.write(" {\n");
        self.indent();
        for item in &t.items {
            match item {
                TraitItem::Function(f) => self.emit_function(f)?,
                TraitItem::Type { name, bounds } => {
                    self.write_indent();
                    self.write("type ");
                    self.write(&name.name);
                    if !bounds.is_empty() {
                        self.write(": ");
                        for (i, b) in bounds.iter().enumerate() {
                            if i > 0 { self.write(" + "); }
                            self.emit_type(b)?;
                        }
                    }
                    self.write(";\n");
                }
                TraitItem::Const { name, ty } => {
                    self.write_indent();
                    self.write("const ");
                    self.write(&name.name);
                    self.write(": ");
                    self.emit_type(ty)?;
                    self.write(";\n");
                }
            }
        }
        self.dedent();
        self.write_indent();
        self.write("}");
        self.newline();
        Ok(())
    }

    fn emit_impl(&mut self, i: &ImplBlock) -> RustCodegenResult<()> {
        self.write_indent();
        if i.is_unsafe {
            self.write("unsafe ");
        }
        self.write("impl");

        // Emit generics - either from explicit generics or extract from self_ty
        if let Some(ref g) = i.generics {
            self.emit_generics(g)?;
        } else {
            // Try to extract generics from self_ty (e.g., Point<T> → impl<T>)
            if let TypeExpr::Path(path) = &i.self_ty {
                self.emit_inferred_impl_generics(path)?;
            }
        }

        if let Some(ref trait_path) = i.trait_ {
            self.write(" ");
            self.emit_type_path(trait_path)?;
            self.write(" for");
        }

        self.write(" ");
        self.emit_type(&i.self_ty)?;

        // Emit where clause if present
        if let Some(ref wc) = i.where_clause {
            self.emit_where_clause(wc)?;
        }

        self.write(" {\n");
        self.indent();
        for item in &i.items {
            match item {
                ImplItem::Function(f) => self.emit_function(f)?,
                ImplItem::Type(alias) => {
                    self.write_indent();
                    self.write("type ");
                    self.write(&alias.name.name);
                    self.write(" = ");
                    self.emit_type(&alias.ty)?;
                    self.write(";\n");
                }
                ImplItem::Const(c) => {
                    self.write_indent();
                    self.write("const ");
                    self.write(&c.name.name);
                    self.write(": ");
                    self.emit_type(&c.ty)?;
                    self.write(" = ");
                    self.emit_expr(&c.value)?;
                    self.write(";\n");
                }
            }
        }
        self.dedent();
        self.write_indent();
        self.write("}");
        self.newline();
        Ok(())
    }

    fn emit_extern_block(&mut self, eb: &ExternBlock) -> RustCodegenResult<()> {
        self.write_indent();
        self.write("extern \"");
        self.write(&eb.abi);
        self.write("\" {\n");
        self.indent();
        for item in &eb.items {
            match item {
                ExternItem::Function(f) => {
                    self.write_indent();
                    self.write("fn ");
                    self.write(&f.name.name);
                    self.write("(");
                    for (i, param) in f.params.iter().enumerate() {
                        if i > 0 { self.write(", "); }
                        self.emit_param(param)?;
                    }
                    if f.variadic {
                        if !f.params.is_empty() { self.write(", "); }
                        self.write("...");
                    }
                    self.write(")");
                    if let Some(ref ret) = f.return_type {
                        self.write(" -> ");
                        self.emit_type(ret)?;
                    }
                    self.write(";\n");
                }
                ExternItem::Static(s) => {
                    self.write_indent();
                    self.write("static ");
                    if s.mutable { self.write("mut "); }
                    self.write(&s.name.name);
                    self.write(": ");
                    self.emit_type(&s.ty)?;
                    self.write(";\n");
                }
                ExternItem::Type(t) => {
                    self.write_indent();
                    self.write("type ");
                    self.write(&t.name.name);
                    if let Some(ref ty) = t.ty {
                        self.write(" = ");
                        self.emit_type(ty)?;
                    }
                    self.write(";\n");
                }
            }
        }
        self.dedent();
        self.write_indent();
        self.write("}");
        self.newline();
        Ok(())
    }

    fn emit_const(&mut self, c: &ConstDef) -> RustCodegenResult<()> {
        self.write_indent();
        self.emit_visibility(&c.visibility);
        self.write("const ");
        self.write(&c.name.name);
        self.write(": ");
        self.emit_type(&c.ty)?;
        self.write(" = ");
        self.emit_expr(&c.value)?;
        self.write(";\n");
        Ok(())
    }

    fn emit_static(&mut self, s: &StaticDef) -> RustCodegenResult<()> {
        self.write_indent();
        self.emit_visibility(&s.visibility);
        self.write("static ");
        if s.mutable { self.write("mut "); }
        self.write(&s.name.name);
        self.write(": ");
        self.emit_type(&s.ty)?;
        self.write(" = ");
        self.emit_expr(&s.value)?;
        self.write(";\n");
        Ok(())
    }

    fn emit_type_alias(&mut self, a: &TypeAlias) -> RustCodegenResult<()> {
        self.write_indent();
        self.emit_visibility(&a.visibility);
        self.write("type ");
        self.write(&a.name.name);
        if let Some(ref g) = a.generics {
            self.emit_generics(g)?;
        }
        self.write(" = ");
        self.emit_type(&a.ty)?;
        self.write(";\n");
        Ok(())
    }

    fn emit_use(&mut self, u: &UseDecl) -> RustCodegenResult<()> {
        self.write_indent();
        self.emit_visibility(&u.visibility);
        self.write("use ");
        self.emit_use_tree(&u.tree)?;
        self.write(";\n");
        Ok(())
    }

    fn emit_use_tree(&mut self, tree: &UseTree) -> RustCodegenResult<()> {
        match tree {
            UseTree::Path { prefix, suffix } => {
                self.write(&prefix.name);
                self.write("::");
                self.emit_use_tree(suffix)?;
            }
            UseTree::Name(ident) => self.write(&ident.name),
            UseTree::Rename { name, alias } => {
                self.write(&name.name);
                self.write(" as ");
                self.write(&alias.name);
            }
            UseTree::Glob => self.write("*"),
            UseTree::Group(items) => {
                self.write("{");
                for (i, item) in items.iter().enumerate() {
                    if i > 0 { self.write(", "); }
                    self.emit_use_tree(item)?;
                }
                self.write("}");
            }
        }
        Ok(())
    }

    fn emit_module(&mut self, m: &Module) -> RustCodegenResult<()> {
        self.write_indent();
        self.emit_visibility(&m.visibility);
        self.write("mod ");
        self.write(&m.name.name);
        if let Some(ref items) = m.items {
            self.write(" {\n");
            self.indent();
            for spanned_item in items {
                self.emit_item(&spanned_item.node)?;
            }
            self.dedent();
            self.write_indent();
            self.write("}");
        } else {
            self.write(";");
        }
        self.newline();
        Ok(())
    }

    // Type emission
    fn emit_type(&mut self, ty: &TypeExpr) -> RustCodegenResult<()> {
        match ty {
            TypeExpr::Path(path) => self.emit_type_path(path),
            TypeExpr::Reference { mutable, inner, lifetime } => {
                self.write("&");
                if let Some(lt) = lifetime {
                    self.write("'");
                    self.write(lt);
                    self.write(" ");
                }
                if *mutable { self.write("mut "); }
                self.emit_type(inner)
            }
            TypeExpr::Pointer { mutable, inner } => {
                self.write("*");
                if *mutable { self.write("mut "); } else { self.write("const "); }
                self.emit_type(inner)
            }
            TypeExpr::Array { element, size } => {
                self.write("[");
                self.emit_type(element)?;
                self.write("; ");
                self.emit_expr(size)?;
                self.write("]");
                Ok(())
            }
            TypeExpr::Slice(inner) => {
                self.write("[");
                self.emit_type(inner)?;
                self.write("]");
                Ok(())
            }
            TypeExpr::Tuple(types) => {
                self.write("(");
                for (i, t) in types.iter().enumerate() {
                    if i > 0 { self.write(", "); }
                    self.emit_type(t)?;
                }
                self.write(")");
                Ok(())
            }
            TypeExpr::Function { params, return_type } => {
                self.write("fn(");
                for (i, p) in params.iter().enumerate() {
                    if i > 0 { self.write(", "); }
                    self.emit_type(p)?;
                }
                self.write(")");
                if let Some(ret) = return_type {
                    self.write(" -> ");
                    self.emit_type(ret)?;
                }
                Ok(())
            }
            TypeExpr::Infer => { self.write("_"); Ok(()) }
            TypeExpr::Never => { self.write("!"); Ok(()) }
            TypeExpr::Lifetime(lt) => { self.write("'"); self.write(lt); Ok(()) }
            TypeExpr::Evidential { inner, .. } => {
                // Strip evidentiality by default (or wrap if preserve_evidence is set)
                self.emit_type(inner)
            }
            TypeExpr::ConstExpr(expr) => {
                // Const generic value - emit the expression
                self.emit_expr(expr)
            }
            TypeExpr::TraitObject(bounds) => {
                self.write("dyn ");
                for (i, b) in bounds.iter().enumerate() {
                    if i > 0 { self.write(" + "); }
                    self.emit_type(b)?;
                }
                Ok(())
            }
            TypeExpr::Hrtb { lifetimes, bound } => {
                self.write("for<");
                for (i, lt) in lifetimes.iter().enumerate() {
                    if i > 0 { self.write(", "); }
                    self.write("'");
                    self.write(lt);
                }
                self.write("> ");
                self.emit_type(bound)
            }
            TypeExpr::Atomic(inner) => {
                // atomic<T> → std::sync::atomic::Atomic<T> (simplified)
                self.write("std::sync::atomic::Atomic");
                self.write("<");
                self.emit_type(inner)?;
                self.write(">");
                Ok(())
            }
            TypeExpr::Linear(inner) | TypeExpr::Affine(inner) | TypeExpr::Relevant(inner) => {
                // Linear/affine/relevant types - just emit the inner type for Rust
                self.emit_type(inner)
            }
            TypeExpr::AssocTypeBinding { name, ty } => {
                // Associated type binding: Output = Type
                // Note: This also gets hit when parser misinterprets `D: DType = F32`
                // In that case, name="DType", ty=F32, but we want just "DType"
                self.write(&name.name);
                self.write(" = ");
                self.emit_type(ty)
            }
            TypeExpr::ImplTrait(bounds) => {
                self.write("impl ");
                for (i, b) in bounds.iter().enumerate() {
                    if i > 0 { self.write(" + "); }
                    self.emit_type(b)?;
                }
                Ok(())
            }
            TypeExpr::QualifiedPath { self_type, trait_path, item_path } => {
                self.write("<");
                self.emit_type(self_type)?;
                if let Some(ref tp) = trait_path {
                    self.write(" as ");
                    self.emit_type_path(tp)?;
                }
                self.write(">::");
                self.emit_type_path(item_path)
            }
            TypeExpr::InlineStruct { .. } | TypeExpr::InlineEnum { .. } => {
                // Inline struct/enum types can't be directly translated
                self.write("/* inline type */");
                Ok(())
            }
            TypeExpr::Cycle { .. } | TypeExpr::Simd { .. } => {
                // Sigil-specific types
                self.write("/* sigil type */");
                Ok(())
            }
        }
    }

    fn emit_type_path(&mut self, path: &TypePath) -> RustCodegenResult<()> {
        for (i, seg) in path.segments.iter().enumerate() {
            if i > 0 { self.write("::"); }
            let name = &seg.ident.name;
            self.write(name);

            // Special handling for Fn traits: Fn<(Args), Return> → Fn(Args) -> Return
            if let Some(ref args) = seg.generics {
                if !args.is_empty() {
                    let is_fn_trait = name == "Fn" || name == "FnMut" || name == "FnOnce";

                    if is_fn_trait && args.len() == 2 {
                        // First arg is the parameter tuple, second is return type
                        self.write("(");
                        // Emit parameters - if first arg is a tuple, unwrap it
                        if let TypeExpr::Tuple(params) = &args[0] {
                            for (j, p) in params.iter().enumerate() {
                                if j > 0 { self.write(", "); }
                                self.emit_type(p)?;
                            }
                        } else {
                            self.emit_type(&args[0])?;
                        }
                        self.write(") -> ");
                        self.emit_type(&args[1])?;
                    } else if is_fn_trait && args.len() == 1 {
                        // Single arg - no return type (returns ())
                        self.write("(");
                        if let TypeExpr::Tuple(params) = &args[0] {
                            for (j, p) in params.iter().enumerate() {
                                if j > 0 { self.write(", "); }
                                self.emit_type(p)?;
                            }
                        } else {
                            self.emit_type(&args[0])?;
                        }
                        self.write(")");
                    } else {
                        // Standard generic syntax
                        self.write("<");
                        for (j, arg) in args.iter().enumerate() {
                            if j > 0 { self.write(", "); }
                            self.emit_type(arg)?;
                        }
                        self.write(">");
                    }
                }
            }
        }
        Ok(())
    }

    /// Emit a path in expression context - uses . for value field access, :: for type paths
    fn emit_expr_path(&mut self, path: &TypePath) -> RustCodegenResult<()> {
        if path.segments.is_empty() {
            return Ok(());
        }

        // Primitive types that start with lowercase but need ::
        // Also includes common custom numeric types from nihil/ML crates
        let primitive_types = [
            "f32", "f64", "f16", "bf16",
            "i8", "i16", "i32", "i64", "i128", "isize",
            "u8", "u16", "u32", "u64", "u128", "usize",
            "bool", "char", "str",
            // Custom numeric types (nihil, half, etc.)
            "f8e4m3", "f8e5m2", "tf32", "c32", "c64", "int4",
        ];

        // Module/crate names that start with lowercase but need ::
        let module_roots = [
            "std", "crate", "super", "self", "core", "alloc", "rand", "serde", "tokio", "async_trait",
            // Nihil ML framework crates
            "nihil_core", "nihil_ops", "nihil_nn", "nihil_optim", "nihil_transformer",
            "nihil_cuda", "nihil_cpu", "nihil_linalg", "nihil_quant", "nihil_distributed",
        ];

        // Standard library submodules (lowercase but are modules, not methods)
        let std_submodules = [
            "ptr", "mem", "slice", "str", "vec", "io", "fs", "env", "thread",
            "sync", "cell", "fmt", "ops", "cmp", "hash", "iter", "collections",
            "marker", "any", "convert", "result", "option", "alloc", "f32", "f64",
            "i8", "i16", "i32", "i64", "u8", "u16", "u32", "u64", "usize", "isize",
            "num", "ffi", "os", "path", "time", "net", "process", "rc", "arc",
            "borrow", "clone", "default", "error", "panic", "boxed",
            // Nihil submodules
            "view", "tensor", "shape", "dtype", "device", "storage", "autograd", "rns",
            // Common lowercase submodule names
            "unary", "binary", "reduce", "index", "compare", "math", "utils",
        ];

        // Check if a name is a type/module (needs :: separator)
        let is_type_or_module = |name: &str| -> bool {
            name.chars().next().map_or(false, |c| c.is_uppercase())
                || primitive_types.contains(&name)
                || module_roots.contains(&name)
                || std_submodules.contains(&name)
                // Snake_case names with underscore are typically crate/module names
                || name.contains('_')
        };

        // Check if first segment is a local binding - if so, use . for all subsequent
        let first_is_local = path.segments.first()
            .map(|s| self.local_bindings.contains(&s.ident.name))
            .unwrap_or(false);

        for (i, seg) in path.segments.iter().enumerate() {
            if i > 0 {
                // If first segment is a local binding, always use . for method/field access
                if first_is_local {
                    self.write(".");
                } else {
                    let prev_name = path.segments[i - 1].ident.name.as_str();
                    let curr_name = seg.ident.name.as_str();

                    // Use :: if:
                    // 1. Current segment starts with uppercase (entering a type/module)
                    // 2. Previous segment was a type/module (continuing type path)
                    // 3. Previous was lowercase crate name and current is uppercase (crate::Type)
                    let use_double_colon = is_type_or_module(curr_name)
                        || is_type_or_module(prev_name)
                        || (i == 1 && curr_name.chars().next().map_or(false, |c| c.is_uppercase()));

                    if use_double_colon {
                        self.write("::");
                    } else {
                        self.write(".");
                    }
                }
            }
            // Map special names
            let name = seg.ident.name.as_str();
            match name {
                "this" => self.write("self"),
                "This" => self.write("Self"),
                _ => self.write(name),
            }
            if let Some(ref args) = seg.generics {
                if !args.is_empty() {
                    self.write("::<");
                    for (j, arg) in args.iter().enumerate() {
                        if j > 0 { self.write(", "); }
                        self.emit_type(arg)?;
                    }
                    self.write(">");
                }
            }
        }
        Ok(())
    }

    fn emit_generics(&mut self, g: &Generics) -> RustCodegenResult<()> {
        if g.params.is_empty() { return Ok(()); }
        self.write("<");
        for (i, param) in g.params.iter().enumerate() {
            if i > 0 { self.write(", "); }
            match param {
                GenericParam::Type { name, bounds, default, .. } => {
                    self.write(&name.name);
                    if !bounds.is_empty() {
                        self.write(": ");
                        for (j, b) in bounds.iter().enumerate() {
                            if j > 0 { self.write(" + "); }
                            self.emit_type(b)?;
                        }
                    }
                    if let Some(ref def) = default {
                        self.write(" = ");
                        self.emit_type(def)?;
                    }
                }
                GenericParam::Lifetime(name) => {
                    self.write("'");
                    self.write(name);
                }
                GenericParam::Const { name, ty, default } => {
                    self.write("const ");
                    self.write(&name.name);
                    self.write(": ");
                    self.emit_type(ty)?;
                    if let Some(ref def) = default {
                        self.write(" = ");
                        self.emit_expr(def)?;
                    }
                }
            }
        }
        self.write(">");
        Ok(())
    }

    /// Extract and emit inferred generic parameters from a type path.
    /// For `Point<T>`, emits `<T>`. For `Point<f64>`, emits nothing (concrete type).
    fn emit_inferred_impl_generics(&mut self, path: &TypePath) -> RustCodegenResult<()> {
        // Collect all type parameters that look like generic parameters (single uppercase letter or
        // PascalCase names that aren't concrete types)
        let mut generic_params: Vec<String> = Vec::new();
        let mut const_params: Vec<(String, String)> = Vec::new(); // (name, type)

        for seg in &path.segments {
            if let Some(ref args) = seg.generics {
                for arg in args {
                    self.collect_inferred_generics(arg, &mut generic_params, &mut const_params);
                }
            }
        }

        if generic_params.is_empty() && const_params.is_empty() {
            return Ok(());
        }

        self.write("<");
        let mut first = true;
        for param in &generic_params {
            if !first { self.write(", "); }
            first = false;
            self.write(param);
        }
        for (name, ty) in &const_params {
            if !first { self.write(", "); }
            first = false;
            self.write("const ");
            self.write(name);
            self.write(": ");
            self.write(ty);
        }
        self.write(">");
        Ok(())
    }

    /// Collect generic type parameters from a type expression.
    fn collect_inferred_generics(&self, ty: &TypeExpr, type_params: &mut Vec<String>, const_params: &mut Vec<(String, String)>) {
        match ty {
            TypeExpr::Path(path) => {
                // Single-segment path that's a type variable (like T, U, etc.)
                if path.segments.len() == 1 {
                    let name = &path.segments[0].ident.name;
                    // Heuristic: single uppercase letter or short PascalCase names that aren't
                    // common concrete types are likely type parameters
                    if self.looks_like_type_param(name) && !type_params.contains(name) {
                        type_params.push(name.clone());
                    }
                    // Recurse into generic args
                    if let Some(ref args) = path.segments[0].generics {
                        for arg in args {
                            self.collect_inferred_generics(arg, type_params, const_params);
                        }
                    }
                }
            }
            TypeExpr::Array { element, .. } => {
                self.collect_inferred_generics(element, type_params, const_params);
            }
            TypeExpr::Slice(inner) => {
                self.collect_inferred_generics(inner, type_params, const_params);
            }
            TypeExpr::Reference { inner, .. } => {
                self.collect_inferred_generics(inner, type_params, const_params);
            }
            TypeExpr::Tuple(types) => {
                for t in types {
                    self.collect_inferred_generics(t, type_params, const_params);
                }
            }
            TypeExpr::Function { params, return_type, .. } => {
                for p in params {
                    self.collect_inferred_generics(p, type_params, const_params);
                }
                if let Some(ret) = return_type {
                    self.collect_inferred_generics(ret, type_params, const_params);
                }
            }
            _ => {}
        }
    }

    /// Heuristic to determine if a name looks like a type parameter.
    fn looks_like_type_param(&self, name: &str) -> bool {
        // Single uppercase letter is almost certainly a type param
        if name.len() == 1 && name.chars().next().map_or(false, |c| c.is_uppercase()) {
            return true;
        }
        // Common concrete types that should NOT be treated as type params
        let concrete_types = [
            "String", "Vec", "Option", "Result", "Box", "Rc", "Arc", "Cell", "RefCell",
            "HashMap", "HashSet", "BTreeMap", "BTreeSet", "VecDeque",
            "Self", "bool", "char",
        ];
        if concrete_types.contains(&name) {
            return false;
        }
        // Numeric types
        if name.starts_with("i") || name.starts_with("u") || name.starts_with("f") {
            if name.len() <= 4 && name[1..].chars().all(|c| c.is_ascii_digit()) {
                return false;
            }
        }
        // Other short PascalCase names might be type params
        name.len() <= 3 && name.chars().next().map_or(false, |c| c.is_uppercase())
    }

    fn emit_function_attrs(&mut self, attrs: &FunctionAttrs) -> RustCodegenResult<()> {
        use crate::ast::InlineHint;

        // #[no_mangle] - must come before extern "C"
        if attrs.no_mangle || attrs.export {
            self.write_indent();
            self.writeln("#[no_mangle]");
        }

        // #[inline], #[inline(always)], #[inline(never)]
        if let Some(ref hint) = attrs.inline {
            self.write_indent();
            match hint {
                InlineHint::Hint => self.writeln("#[inline]"),
                InlineHint::Always => self.writeln("#[inline(always)]"),
                InlineHint::Never => self.writeln("#[inline(never)]"),
            }
        }

        // #[naked]
        if attrs.naked {
            self.write_indent();
            self.writeln("#[naked]");
        }

        // #[link_section = "..."]
        if let Some(ref section) = attrs.link_section {
            self.write_indent();
            self.write("#[link_section = \"");
            self.write(section);
            self.writeln("\"]");
        }

        // #[panic_handler]
        if attrs.panic_handler {
            self.write_indent();
            self.writeln("#[panic_handler]");
        }

        // #[entry]
        if attrs.entry {
            self.write_indent();
            self.writeln("#[entry]");
        }

        // #[interrupt = N]
        if let Some(n) = attrs.interrupt {
            self.write_indent();
            self.write(&format!("#[interrupt({})]\n", n));
        }

        // #[repr(align(N))]
        if let Some(n) = attrs.align {
            self.write_indent();
            self.write(&format!("#[repr(align({}))]\n", n));
        }

        Ok(())
    }

    fn emit_visibility(&mut self, vis: &Visibility) {
        match vis {
            Visibility::Public => self.write("pub "),
            Visibility::Crate => self.write("pub(crate) "),
            Visibility::Super => self.write("pub(super) "),
            Visibility::Private => {}
        }
    }

    fn emit_attr_args(&mut self, args: &AttrArgs) -> RustCodegenResult<()> {
        match args {
            AttrArgs::Paren(items) => {
                self.write("(");
                for (i, arg) in items.iter().enumerate() {
                    if i > 0 { self.write(", "); }
                    self.emit_attr_arg(arg)?;
                }
                self.write(")");
            }
            AttrArgs::Eq(expr) => {
                self.write(" = ");
                self.emit_expr(expr)?;
            }
        }
        Ok(())
    }

    fn emit_attr_arg(&mut self, arg: &AttrArg) -> RustCodegenResult<()> {
        match arg {
            AttrArg::Ident(ident) => self.write(&ident.name),
            AttrArg::Literal(lit) => self.emit_literal(lit)?,
            AttrArg::Nested(attr) => {
                self.write(&attr.name.name);
                if let Some(args) = &attr.args {
                    self.emit_attr_args(args)?;
                }
            }
            AttrArg::KeyValue { key, value } => {
                self.write(&key.name);
                self.write(" = ");
                self.emit_expr(value)?;
            }
        }
        Ok(())
    }

    fn emit_param(&mut self, param: &Param) -> RustCodegenResult<()> {
        // Check if this is a self parameter by looking at the pattern
        // Handle Pattern::Ident { name: "this" } with reference type
        if let Pattern::Ident { name, mutable, .. } = &param.pattern {
            if name.name == "self" || name.name == "this" {
                match &param.ty {
                    TypeExpr::Reference { mutable: ref_mut, .. } => {
                        if *ref_mut {
                            self.write("&mut self");
                        } else {
                            self.write("&self");
                        }
                    }
                    _ => {
                        if *mutable {
                            self.write("mut self");
                        } else {
                            self.write("self");
                        }
                    }
                }
                return Ok(());
            }
        }
        // Handle Pattern::Ref { pattern: Ident { name: "this" } }
        if let Pattern::Ref { mutable, pattern } = &param.pattern {
            if let Pattern::Ident { name, .. } = pattern.as_ref() {
                if name.name == "self" || name.name == "this" {
                    if *mutable {
                        self.write("&mut self");
                    } else {
                        self.write("&self");
                    }
                    return Ok(());
                }
            }
        }
        self.emit_pattern(&param.pattern)?;
        self.write(": ");
        self.emit_type(&param.ty)?;
        Ok(())
    }

    // Expression emission
    fn emit_expr(&mut self, expr: &Expr) -> RustCodegenResult<()> {
        match expr {
            Expr::Literal(lit) => self.emit_literal(lit),
            Expr::Path(path) => self.emit_expr_path(path),
            Expr::Binary { op, left, right } => {
                // Check for misidentified pipe-as-BitOr patterns like `iter | sorted`
                // These should be converted to method chains: `iter.sorted()`
                if *op == BinOp::BitOr {
                    if let Some(method) = Self::detect_pipe_method(right) {
                        self.emit_expr(left)?;
                        self.write(&method);
                        return Ok(());
                    }
                    // Also handle pipe function calls like `x | join(",")`
                    if let Expr::Call { func, args } = right.as_ref() {
                        if let Expr::Path(path) = func.as_ref() {
                            if path.segments.len() == 1 {
                                let name = path.segments[0].ident.name.as_str();
                                // Known pipe functions
                                if matches!(name, "join" | "take" | "skip" | "nth" | "chunks" | "filter" | "map" | "fold" | "reduce" | "for_each" | "find" | "position" | "partition" | "unzip" | "zip" | "chain" | "intersperse" | "step_by" | "inspect") {
                                    self.emit_expr(left)?;
                                    self.write(".");
                                    self.write(name);
                                    self.write("(");
                                    for (i, arg) in args.iter().enumerate() {
                                        if i > 0 { self.write(", "); }
                                        self.emit_expr(arg)?;
                                    }
                                    self.write(")");
                                    return Ok(());
                                }
                            }
                        }
                    }
                }

                // Check if left operand needs parentheses
                let left_needs_parens = Self::needs_parens_for_binop(left, op, true);
                if left_needs_parens { self.write("("); }
                self.emit_expr(left)?;
                if left_needs_parens { self.write(")"); }

                self.write(" ");
                self.emit_binop(op);
                self.write(" ");

                // Check if right operand needs parentheses
                let right_needs_parens = Self::needs_parens_for_binop(right, op, false);
                if right_needs_parens { self.write("("); }
                self.emit_expr(right)?;
                if right_needs_parens { self.write(")"); }

                Ok(())
            }
            Expr::Unary { op, expr } => {
                self.emit_unop(op);
                self.emit_expr(expr)
            }
            Expr::Call { func, args } => {
                // Check if this is a Rust macro call
                if let Expr::Path(path) = func.as_ref() {
                    if path.segments.len() == 1 {
                        let name = &path.segments[0].ident.name;
                        match name.as_str() {
                            "println" | "print" | "eprintln" | "eprint" => {
                                self.write(name);
                                self.write("!(");
                                if args.is_empty() {
                                    // println!()
                                } else {
                                    // Check if first arg is a format string literal
                                    let first_is_format = if let Expr::Literal(Literal::String(s)) = &args[0] {
                                        s.contains("{}")
                                    } else {
                                        false
                                    };

                                    if first_is_format {
                                        // Pass format string through directly
                                        for (i, arg) in args.iter().enumerate() {
                                            if i > 0 { self.write(", "); }
                                            self.emit_expr(arg)?;
                                        }
                                    } else {
                                        // Generate format string: println!("{}", arg) or println!("{} {}", a, b)
                                        self.write("\"");
                                        for i in 0..args.len() {
                                            if i > 0 { self.write(" "); }
                                            self.write("{}");
                                        }
                                        self.write("\"");
                                        for arg in args {
                                            self.write(", ");
                                            self.emit_expr(arg)?;
                                        }
                                    }
                                }
                                self.write(")");
                                return Ok(());
                            }
                            "format" => {
                                self.write("format!(");
                                if !args.is_empty() {
                                    // Check if first arg is a format string literal
                                    let first_is_format = if let Expr::Literal(Literal::String(s)) = &args[0] {
                                        s.contains("{}")
                                    } else {
                                        false
                                    };

                                    if first_is_format {
                                        for (i, arg) in args.iter().enumerate() {
                                            if i > 0 { self.write(", "); }
                                            self.emit_expr(arg)?;
                                        }
                                    } else {
                                        self.write("\"");
                                        for i in 0..args.len() {
                                            if i > 0 { self.write(" "); }
                                            self.write("{}");
                                        }
                                        self.write("\"");
                                        for arg in args {
                                            self.write(", ");
                                            self.emit_expr(arg)?;
                                        }
                                    }
                                }
                                self.write(")");
                                return Ok(());
                            }
                            "panic" => {
                                self.write("panic!(");
                                for (i, arg) in args.iter().enumerate() {
                                    if i > 0 { self.write(", "); }
                                    self.emit_expr(arg)?;
                                }
                                self.write(")");
                                return Ok(());
                            }
                            "assert" | "assert_eq" | "assert_ne" | "debug_assert" => {
                                self.write(name);
                                self.write("!(");
                                for (i, arg) in args.iter().enumerate() {
                                    if i > 0 { self.write(", "); }
                                    self.emit_expr(arg)?;
                                }
                                self.write(")");
                                return Ok(());
                            }
                            "vec" => {
                                self.write("vec![");
                                for (i, arg) in args.iter().enumerate() {
                                    if i > 0 { self.write(", "); }
                                    self.emit_expr(arg)?;
                                }
                                self.write("]");
                                return Ok(());
                            }
                            "dbg" => {
                                self.write("dbg!(");
                                for (i, arg) in args.iter().enumerate() {
                                    if i > 0 { self.write(", "); }
                                    self.emit_expr(arg)?;
                                }
                                self.write(")");
                                return Ok(());
                            }
                            _ => {} // Fall through to regular call
                        }
                    }
                }
                // Regular function call
                self.emit_expr(func)?;
                self.write("(");
                for (i, arg) in args.iter().enumerate() {
                    if i > 0 { self.write(", "); }
                    self.emit_expr(arg)?;
                }
                self.write(")");
                Ok(())
            }
            Expr::MethodCall { receiver, method, type_args, args } => {
                // Cast and Binary expressions need parens when used as method receivers
                // e.g., (x as T).method(), (a + b).method()
                let needs_parens = matches!(receiver.as_ref(),
                    Expr::Cast { .. } | Expr::Binary { .. } | Expr::Unary { .. } | Expr::Range { .. }
                );
                if needs_parens { self.write("("); }
                self.emit_expr(receiver)?;
                if needs_parens { self.write(")"); }
                self.write(".");
                self.write(&method.name);
                // Emit turbofish type arguments if present
                if let Some(targs) = type_args {
                    if !targs.is_empty() {
                        self.write("::<");
                        for (i, ty) in targs.iter().enumerate() {
                            if i > 0 { self.write(", "); }
                            self.emit_type(ty)?;
                        }
                        self.write(">");
                    }
                }
                self.write("(");
                for (i, arg) in args.iter().enumerate() {
                    if i > 0 { self.write(", "); }
                    self.emit_expr(arg)?;
                }
                self.write(")");
                Ok(())
            }
            Expr::Field { expr, field } => {
                // Cast and Binary expressions need parens when used as field receivers
                // e.g., (x as T).field, (a + b).field
                let needs_parens = matches!(expr.as_ref(),
                    Expr::Cast { .. } | Expr::Binary { .. } | Expr::Unary { .. } | Expr::Range { .. }
                );
                if needs_parens { self.write("("); }
                self.emit_expr(expr)?;
                if needs_parens { self.write(")"); }
                self.write(".");
                self.write(&field.name);
                Ok(())
            }
            Expr::Index { expr, index } => {
                self.emit_expr(expr)?;
                self.write("[");
                self.emit_expr(index)?;
                self.write("]");
                Ok(())
            }
            Expr::Block(block) => self.emit_block(block),
            Expr::If { condition, then_branch, else_branch } => {
                self.write("if ");
                self.emit_expr(condition)?;
                self.write(" ");
                self.emit_block(then_branch)?;
                if let Some(eb) = else_branch {
                    self.write(" else ");
                    self.emit_expr(eb)?;
                }
                Ok(())
            }
            Expr::Match { expr, arms } => {
                self.write("match ");
                self.emit_expr(expr)?;
                self.write(" {\n");
                self.indent();
                for arm in arms {
                    self.write_indent();
                    self.emit_pattern(&arm.pattern)?;
                    if let Some(ref guard) = arm.guard {
                        self.write(" if ");
                        self.emit_expr(guard)?;
                    }
                    self.write(" => ");
                    self.emit_expr(&arm.body)?;
                    self.write(",\n");
                }
                self.dedent();
                self.write_indent();
                self.write("}");
                Ok(())
            }
            Expr::Loop { label, body } => {
                if let Some(l) = label {
                    self.write("'");
                    self.write(&l.name);
                    self.write(": ");
                }
                self.write("loop ");
                self.emit_block_inline(body)
            }
            Expr::While { label, condition, body } => {
                if let Some(l) = label {
                    self.write("'");
                    self.write(&l.name);
                    self.write(": ");
                }
                self.write("while ");
                self.emit_expr(condition)?;
                self.write(" ");
                self.emit_block_inline(body)
            }
            Expr::For { label, pattern, iter, body } => {
                if let Some(l) = label {
                    self.write("'");
                    self.write(&l.name);
                    self.write(": ");
                }
                self.write("for ");
                self.emit_pattern(pattern)?;
                self.write(" in ");
                self.emit_expr(iter)?;
                self.write(" ");
                self.emit_block_inline(body)
            }
            Expr::Return(val) => {
                self.write("return");
                if let Some(v) = val {
                    self.write(" ");
                    self.emit_expr(v)?;
                }
                Ok(())
            }
            Expr::Break { label, value } => {
                self.write("break");
                if let Some(l) = label {
                    self.write(" '");
                    self.write(&l.name);
                }
                if let Some(v) = value {
                    self.write(" ");
                    self.emit_expr(v)?;
                }
                Ok(())
            }
            Expr::Continue { label } => {
                self.write("continue");
                if let Some(l) = label {
                    self.write(" '");
                    self.write(&l.name);
                }
                Ok(())
            }
            Expr::Closure { params, body, is_move, .. } => {
                if *is_move { self.write("move "); }
                self.write("|");
                for (i, p) in params.iter().enumerate() {
                    if i > 0 { self.write(", "); }
                    self.emit_pattern(&p.pattern)?;
                    if let Some(ref ty) = p.ty {
                        self.write(": ");
                        self.emit_type(ty)?;
                    }
                }
                self.write("| ");
                self.emit_expr(body)
            }
            Expr::Struct { path, fields, rest } => {
                self.emit_type_path(path)?;
                self.write(" { ");
                for (i, field) in fields.iter().enumerate() {
                    if i > 0 { self.write(", "); }
                    self.write(&field.name.name);
                    if let Some(ref v) = field.value {
                        self.write(": ");
                        self.emit_expr(v)?;
                    }
                }
                if let Some(r) = rest {
                    if !fields.is_empty() { self.write(", "); }
                    self.write("..");
                    self.emit_expr(r)?;
                }
                self.write(" }");
                Ok(())
            }
            Expr::Array(elements) => {
                self.write("[");
                for (i, e) in elements.iter().enumerate() {
                    if i > 0 { self.write(", "); }
                    self.emit_expr(e)?;
                }
                self.write("]");
                Ok(())
            }
            Expr::ArrayRepeat { value, count } => {
                self.write("[");
                self.emit_expr(value)?;
                self.write("; ");
                self.emit_expr(count)?;
                self.write("]");
                Ok(())
            }
            Expr::Tuple(elements) => {
                self.write("(");
                for (i, e) in elements.iter().enumerate() {
                    if i > 0 { self.write(", "); }
                    self.emit_expr(e)?;
                }
                if elements.len() == 1 { self.write(","); }
                self.write(")");
                Ok(())
            }
            Expr::Range { start, end, inclusive } => {
                if let Some(s) = start { self.emit_expr(s)?; }
                self.write(if *inclusive { "..=" } else { ".." });
                if let Some(e) = end { self.emit_expr(e)?; }
                Ok(())
            }
            Expr::Cast { expr, ty } => {
                // Binary expressions inside casts need parentheses to preserve precedence
                // e.g., (bits >> 23) as i32 - inner parens prevent: bits >> (23 as i32)
                let needs_inner_parens = matches!(expr.as_ref(), Expr::Binary { .. });
                if needs_inner_parens { self.write("("); }
                self.emit_expr(expr)?;
                if needs_inner_parens { self.write(")"); }
                self.write(" as ");
                self.emit_type(ty)?;
                Ok(())
            }
            Expr::Try(inner) => {
                self.emit_expr(inner)?;
                self.write("?");
                Ok(())
            }
            Expr::Await { expr, .. } => {
                self.emit_expr(expr)?;
                self.write(".await");
                Ok(())
            }
            Expr::Unsafe(block) => {
                self.write("unsafe ");
                self.emit_block(block)
            }
            Expr::Pipe { expr, operations } => self.emit_pipe(expr, operations),
            Expr::Incorporation { segments } => {
                // Helper to check if a name is a type/module
                let is_type_or_module = |name: &str| -> bool {
                    let module_roots = ["std", "crate", "super", "self", "core", "alloc"];
                    name.chars().next().map_or(false, |c| c.is_uppercase())
                        || module_roots.contains(&name)
                };

                for (i, seg) in segments.iter().enumerate() {
                    let curr_name = seg.name.name.as_str();
                    if i == 0 {
                        // First segment: emit identifier
                        // Map special names
                        match curr_name {
                            "this" | "self" => self.write("self"),
                            "This" | "Self" => self.write("Self"),
                            _ => self.write(curr_name),
                        }
                    } else {
                        let prev_name = segments[i - 1].name.name.as_str();
                        // Determine separator: :: for type paths, . for value access
                        let use_double_colon = is_type_or_module(curr_name)
                            || is_type_or_module(prev_name)
                            || (i == 1 && curr_name.chars().next().map_or(false, |c| c.is_uppercase()));

                        if let Some(ref args) = seg.args {
                            // Has args - method/function call
                            if use_double_colon {
                                self.write("::");
                            } else {
                                self.write(".");
                            }
                            self.write(curr_name);
                            self.write("(");
                            for (j, arg) in args.iter().enumerate() {
                                if j > 0 { self.write(", "); }
                                self.emit_expr(arg)?;
                            }
                            self.write(")");
                        } else {
                            // No args - field access or module path
                            if use_double_colon {
                                self.write("::");
                            } else {
                                self.write(".");
                            }
                            self.write(curr_name);
                        }
                    }
                }
                Ok(())
            }
            Expr::Morpheme { kind, body } => {
                // Standalone morpheme application
                match kind {
                    MorphemeKind::Transform => {
                        self.write("(");
                        self.emit_expr(body)?;
                        self.write(")");
                    }
                    MorphemeKind::Sum => self.write(".sum::<_>()"),
                    MorphemeKind::Product => self.write(".product::<_>()"),
                    MorphemeKind::First => self.write(".next()"),
                    MorphemeKind::Last => self.write(".last()"),
                    MorphemeKind::Sort => self.write(".sorted()"),
                    _ => {
                        self.write("/* morpheme */");
                        self.emit_expr(body)?;
                    }
                }
                Ok(())
            }
            Expr::Assign { target, value } => {
                self.emit_expr(target)?;
                self.write(" = ");
                self.emit_expr(value)
            }
            Expr::AddrOf { mutable, expr } => {
                self.write("&");
                if *mutable { self.write("mut "); }
                self.emit_expr(expr)
            }
            Expr::Deref(inner) => {
                self.write("*");
                self.emit_expr(inner)
            }
            Expr::Range { start, end, inclusive } => {
                if let Some(s) = start {
                    self.emit_expr(s)?;
                }
                if *inclusive {
                    self.write("..=");
                } else {
                    self.write("..");
                }
                if let Some(e) = end {
                    self.emit_expr(e)?;
                }
                Ok(())
            }
            Expr::Return(val) => {
                self.write("return");
                if let Some(v) = val {
                    self.write(" ");
                    self.emit_expr(v)?;
                }
                Ok(())
            }
            Expr::Break { label, value } => {
                self.write("break");
                if let Some(l) = label {
                    self.write(" '");
                    self.write(&l.name);
                }
                if let Some(v) = value {
                    self.write(" ");
                    self.emit_expr(v)?;
                }
                Ok(())
            }
            Expr::Continue { label } => {
                self.write("continue");
                if let Some(l) = label {
                    self.write(" '");
                    self.write(&l.name);
                }
                Ok(())
            }
            Expr::Async { block, is_move } => {
                if *is_move {
                    self.write("async move ");
                } else {
                    self.write("async ");
                }
                self.emit_block(block)
            }
            Expr::Let { pattern, value } => {
                self.write("let ");
                self.emit_pattern(pattern)?;
                self.write(" = ");
                self.emit_expr(value)
            }
            Expr::Macro { path, tokens } => {
                // Translate Sigil symbols to Rust in macro tokens
                let rust_tokens = tokens
                    .replace("· ", "::")  // middledot+space → :: (no space)
                    .replace('·', "::")   // middledot → ::
                    .replace("Δ", "mut")  // mutable marker
                    .replace("→", "->")   // arrow
                    .replace("≔", "let")  // binding
                    .replace("⌥", "match"); // match (for comments)

                let trimmed = rust_tokens.trim();

                // Check if this is a certainty struct literal: TypeName! { field: value, ... }
                // These should be emitted as regular struct literals, not macro invocations.
                // Detect by: path starts with uppercase + tokens are { field : value, ... }
                let first_seg_name = path.segments.first().map(|s| s.ident.name.as_str()).unwrap_or("");
                let looks_like_type = first_seg_name.chars().next().map_or(false, |c| c.is_uppercase());
                let looks_like_struct_body = trimmed.starts_with('{') && trimmed.ends_with('}')
                    && (trimmed.contains(':') || trimmed == "{}");

                if looks_like_type && looks_like_struct_body {
                    // Emit as struct literal: TypeName { ... }
                    self.emit_type_path(path)?;
                    self.write(" ");
                    // Clean up evidentiality markers from field values (remove trailing !)
                    let cleaned = Self::clean_struct_tokens(trimmed);
                    self.write(&cleaned);
                } else {
                    // Regular macro invocation: path!(tokens)
                    self.emit_type_path(path)?;
                    self.write("!");
                    if trimmed.starts_with('(') || trimmed.starts_with('[') || trimmed.starts_with('{') {
                        self.write(&rust_tokens);
                    } else {
                        self.write("(");
                        self.write(&rust_tokens);
                        self.write(")");
                    }
                }
                Ok(())
            }
            Expr::Evidential { expr, evidentiality } => {
                // For Rust codegen, ? evidentiality becomes the try operator
                // This handles write!(...)? and other Result-returning expressions
                self.emit_expr(expr)?;
                if matches!(evidentiality, crate::ast::Evidentiality::Uncertain) {
                    self.write("?");
                }
                Ok(())
            }
            Expr::ArrayRepeat { value, count } => {
                self.write("[");
                self.emit_expr(value)?;
                self.write("; ");
                self.emit_expr(count)?;
                self.write("]");
                Ok(())
            }
            _ => { self.write("/* TODO: expr */"); Ok(()) }
        }
    }

    fn emit_pipe(&mut self, source: &Expr, ops: &[PipeOp]) -> RustCodegenResult<()> {
        self.emit_expr(source)?;
        self.write(".iter()");
        for op in ops {
            match op {
                PipeOp::Transform(f) => {
                    self.write(".map(");
                    self.emit_expr(f)?;
                    self.write(")");
                }
                PipeOp::Filter(p) => {
                    self.write(".filter(");
                    self.emit_expr(p)?;
                    self.write(")");
                }
                PipeOp::ReduceSum => self.write(".sum::<_>()"),
                PipeOp::ReduceProd => self.write(".product::<_>()"),
                PipeOp::ReduceMin => self.write(".min()"),
                PipeOp::ReduceMax => self.write(".max()"),
                PipeOp::ReduceAll => self.write(".all(|x| *x)"),
                PipeOp::ReduceAny => self.write(".any(|x| *x)"),
                PipeOp::ReduceConcat => self.write(".collect::<String>()"),
                PipeOp::Reduce(f) => {
                    self.write(".reduce(");
                    self.emit_expr(f)?;
                    self.write(")");
                }
                PipeOp::ReduceWithInit(init, f) => {
                    self.write(".fold(");
                    self.emit_expr(init)?;
                    self.write(", ");
                    self.emit_expr(f)?;
                    self.write(")");
                }
                PipeOp::First => self.write(".next()"),
                PipeOp::Last => self.write(".last()"),
                PipeOp::Nth(n) => {
                    self.write(".nth(");
                    self.emit_expr(n)?;
                    self.write(")");
                }
                PipeOp::Next => self.write(".next()"),
                PipeOp::Middle => self.write("/* median - requires collect */"),
                PipeOp::Choice => self.write("/* random - requires rand */"),
                PipeOp::Sort(_) => self.write(".sorted()"),
                PipeOp::SortBy(f) => {
                    self.write(".sorted_by(");
                    self.emit_expr(f)?;
                    self.write(")");
                }
                PipeOp::Method { name, type_args, args } => {
                    // Handle special morpheme names
                    match name.name.as_str() {
                        "Σ" | "sum" => { self.write(".sum::<_>()"); }
                        "Π" | "prod" | "product" => { self.write(".product::<_>()"); }
                        "α" | "first" => { self.write(".next()"); }
                        "ω" | "last" => { self.write(".last()"); }
                        "σ" | "sort" => { self.write(".sorted()"); }
                        "δ" | "distinct" | "unique" => { self.write(".collect::<std::collections::HashSet<_>>().into_iter()"); }
                        "μ" | "middle" => { self.write("/* median */"); }
                        "χ" | "choice" => { self.write("/* random */"); }
                        "ξ" | "next" => { self.write(".next()"); }
                        _ => {
                            self.write(".");
                            self.write(&name.name);
                            if let Some(ref targs) = type_args {
                                if !targs.is_empty() {
                                    self.write("::<");
                                    for (i, t) in targs.iter().enumerate() {
                                        if i > 0 { self.write(", "); }
                                        self.emit_type(t)?;
                                    }
                                    self.write(">");
                                }
                            }
                            self.write("(");
                            for (i, arg) in args.iter().enumerate() {
                                if i > 0 { self.write(", "); }
                                self.emit_expr(arg)?;
                            }
                            self.write(")");
                        }
                    }
                }
                PipeOp::Call(f) => {
                    self.write(".map(|x| (");
                    self.emit_expr(f)?;
                    self.write(")(x))");
                }
                PipeOp::Await => self.write(".await"),
                PipeOp::Parallel(_) => {
                    self.write(".par_iter()");
                }
                PipeOp::Gpu(_) => {
                    self.write("/* GPU compute - requires CUDA/OpenCL */");
                }
                PipeOp::Match(arms) => {
                    self.write(".map(|x| match x { ");
                    for arm in arms {
                        self.emit_pattern(&arm.pattern)?;
                        if let Some(ref guard) = arm.guard {
                            self.write(" if ");
                            self.emit_expr(guard)?;
                        }
                        self.write(" => ");
                        self.emit_expr(&arm.body)?;
                        self.write(", ");
                    }
                    self.write("})");
                }
                PipeOp::TryMap(mapper) => {
                    if let Some(f) = mapper {
                        self.write(".map_err(");
                        self.emit_expr(f)?;
                        self.write(")?");
                    } else {
                        self.write("?");
                    }
                }
                PipeOp::Unique => self.write(".collect::<std::collections::HashSet<_>>().into_iter()"),
                PipeOp::Flatten => self.write(".flatten()"),
                PipeOp::Enumerate => self.write(".enumerate()"),
                PipeOp::Zip(other) => {
                    self.write(".zip(");
                    self.emit_expr(other)?;
                    self.write(".iter())");
                }
                PipeOp::Reverse => self.write(".rev()"),
                PipeOp::Chunks(n) => {
                    self.write(".chunks(");
                    self.emit_expr(n)?;
                    self.write(")");
                }
                PipeOp::Windows(n) => {
                    self.write(".windows(");
                    self.emit_expr(n)?;
                    self.write(")");
                }
                PipeOp::Also(f) => {
                    self.write(".inspect(");
                    self.emit_expr(f)?;
                    self.write(")");
                }
                PipeOp::Apply(f) => {
                    self.write(".map(|mut x| { (");
                    self.emit_expr(f)?;
                    self.write(")(&mut x); x })");
                }
                PipeOp::TakeIf(p) => {
                    self.write(".filter(");
                    self.emit_expr(p)?;
                    self.write(")");
                }
                PipeOp::TakeUnless(p) => {
                    self.write(".filter(|x| !(");
                    self.emit_expr(p)?;
                    self.write(")(x))");
                }
                PipeOp::Let(f) => {
                    self.write(".map(");
                    self.emit_expr(f)?;
                    self.write(")");
                }
                PipeOp::All(p) => {
                    self.write(".all(");
                    self.emit_expr(p)?;
                    self.write(")");
                }
                PipeOp::Any(p) => {
                    self.write(".any(");
                    self.emit_expr(p)?;
                    self.write(")");
                }
                PipeOp::Scan(f) => {
                    self.write(".scan(Default::default(), ");
                    self.emit_expr(f)?;
                    self.write(")");
                }
                PipeOp::Diff => self.write(".zip(.skip(1)).map(|(a, b)| b - a)"),
                PipeOp::SortAsc => self.write(".sorted()"),
                PipeOp::SortDesc => self.write(".sorted().rev()"),
                PipeOp::Cycle(n) => {
                    self.write(".cycle().take(");
                    self.emit_expr(n)?;
                    self.write(")");
                }
                PipeOp::Universal => self.write(".sum::<_>()"),
                PipeOp::Send(_) | PipeOp::Recv | PipeOp::Stream(_) |
                PipeOp::Connect(_) | PipeOp::Close | PipeOp::Header { .. } |
                PipeOp::Body(_) | PipeOp::Timeout(_) | PipeOp::Retry { .. } => {
                    self.write("/* protocol op - requires async runtime */");
                }
                PipeOp::Validate { .. } | PipeOp::Assume { .. } |
                PipeOp::AssertEvidence(_) | PipeOp::PossibilityExtract |
                PipeOp::NecessityVerify => {
                    self.write("/* evidence op - stripped in Rust */");
                }
                PipeOp::Named { prefix, body } => {
                    // Handle named morphemes like |Σ, |Π, |α, |ω, |δ
                    let name = prefix.iter().map(|i| i.name.as_str()).collect::<Vec<_>>().join("::");
                    match name.as_str() {
                        "Σ" | "sum" => self.write(".sum::<_>()"),
                        "Π" | "prod" | "product" => self.write(".product::<_>()"),
                        "α" | "first" => self.write(".next()"),
                        "ω" | "last" => self.write(".last()"),
                        "σ" | "sort" => self.write(".sorted()"),
                        "δ" | "distinct" | "unique" => self.write(".collect::<std::collections::HashSet<_>>().into_iter()"),
                        "μ" | "middle" => self.write("/* median */"),
                        "χ" | "choice" => self.write("/* random */"),
                        "ξ" | "next" => self.write(".next()"),
                        "collect" => self.write(".collect::<Vec<_>>()"),
                        "clone" => self.write(".cloned()"),
                        "copied" => self.write(".copied()"),
                        _ => {
                            self.write(".");
                            self.write(&name);
                            self.write("(");
                            if let Some(b) = body {
                                self.emit_expr(b)?;
                            }
                            self.write(")");
                        }
                    }
                }
                PipeOp::Compose(_) | PipeOp::Gradient(_) | PipeOp::Possibility { .. } |
                PipeOp::Necessity { .. } => {
                    self.write("/* advanced op */");
                }
                _ => self.write("/* TODO: pipe op */"),
            }
        }
        Ok(())
    }

    fn emit_block(&mut self, block: &Block) -> RustCodegenResult<()> {
        self.write("{\n");
        self.indent();
        for stmt in &block.stmts {
            self.emit_stmt(stmt)?;
        }
        if let Some(ref expr) = block.expr {
            self.write_indent();
            self.emit_expr(expr)?;
            self.newline();
        }
        self.dedent();
        self.write_indent();
        self.write("}");
        Ok(())
    }

    fn emit_block_inline(&mut self, block: &Block) -> RustCodegenResult<()> {
        self.write("{\n");
        self.indent();
        for stmt in &block.stmts {
            self.emit_stmt(stmt)?;
        }
        if let Some(ref expr) = block.expr {
            self.write_indent();
            self.emit_expr(expr)?;
            self.newline();
        }
        self.dedent();
        self.write_indent();
        self.write("}");
        Ok(())
    }

    /// Extract binding names from a pattern for local binding tracking
    fn collect_pattern_bindings(&self, pattern: &Pattern, bindings: &mut Vec<String>) {
        match pattern {
            Pattern::Ident { name, .. } => bindings.push(name.name.clone()),
            Pattern::Tuple(elements) => {
                for p in elements {
                    self.collect_pattern_bindings(p, bindings);
                }
            }
            Pattern::Struct { fields, .. } => {
                for f in fields {
                    if let Some(ref pat) = f.pattern {
                        self.collect_pattern_bindings(pat, bindings);
                    } else {
                        // Shorthand: `Point { x, y }` binds x and y
                        bindings.push(f.name.name.clone());
                    }
                }
            }
            Pattern::TupleStruct { fields, .. } => {
                for p in fields {
                    self.collect_pattern_bindings(p, bindings);
                }
            }
            Pattern::Slice(elements) => {
                for p in elements {
                    self.collect_pattern_bindings(p, bindings);
                }
            }
            Pattern::Or(patterns) => {
                // For or-patterns, all branches must bind the same names
                if let Some(first) = patterns.first() {
                    self.collect_pattern_bindings(first, bindings);
                }
            }
            Pattern::Ref { pattern: inner, .. } => {
                self.collect_pattern_bindings(inner, bindings);
            }
            Pattern::RefBinding { name, .. } => {
                bindings.push(name.name.clone());
            }
            // These don't introduce bindings
            Pattern::Wildcard | Pattern::Literal(_) | Pattern::Path(_)
            | Pattern::Range { .. } | Pattern::Rest => {}
        }
    }

    fn emit_stmt(&mut self, stmt: &Stmt) -> RustCodegenResult<()> {
        match stmt {
            Stmt::Let { pattern, ty, init } => {
                // Track local bindings for path resolution
                let mut bindings = Vec::new();
                self.collect_pattern_bindings(pattern, &mut bindings);
                for name in bindings {
                    self.local_bindings.insert(name);
                }

                self.write_indent();
                self.write("let ");
                // Check if pattern has mutability
                self.emit_pattern(pattern)?;
                if let Some(t) = ty {
                    self.write(": ");
                    self.emit_type(t)?;
                }
                if let Some(v) = init {
                    self.write(" = ");
                    self.emit_expr(v)?;
                }
                self.write(";\n");
            }
            Stmt::LetElse { pattern, ty, init, else_branch } => {
                // Track local bindings for path resolution
                let mut bindings = Vec::new();
                self.collect_pattern_bindings(pattern, &mut bindings);
                for name in bindings {
                    self.local_bindings.insert(name);
                }

                self.write_indent();
                self.write("let ");
                self.emit_pattern(pattern)?;
                if let Some(t) = ty {
                    self.write(": ");
                    self.emit_type(t)?;
                }
                self.write(" = ");
                self.emit_expr(init)?;
                self.write(" else ");
                self.emit_expr(else_branch)?;
                self.write(";\n");
            }
            Stmt::Expr(e) => {
                self.write_indent();
                self.emit_expr(e)?;
                self.newline();
            }
            Stmt::Semi(e) => {
                self.write_indent();
                self.emit_expr(e)?;
                self.write(";\n");
            }
            Stmt::Item(item) => self.emit_item(item)?,
        }
        Ok(())
    }

    fn emit_pattern(&mut self, pattern: &Pattern) -> RustCodegenResult<()> {
        match pattern {
            Pattern::Ident { name, mutable, .. } => {
                if *mutable { self.write("mut "); }
                self.write(&name.name);
            }
            Pattern::Wildcard => self.write("_"),
            Pattern::Literal(lit) => self.emit_literal(lit)?,
            Pattern::Tuple(patterns) => {
                self.write("(");
                for (i, p) in patterns.iter().enumerate() {
                    if i > 0 { self.write(", "); }
                    self.emit_pattern(p)?;
                }
                self.write(")");
            }
            Pattern::Path(path) => self.emit_type_path(path)?,
            Pattern::TupleStruct { path, fields } => {
                self.emit_type_path(path)?;
                self.write("(");
                for (i, p) in fields.iter().enumerate() {
                    if i > 0 { self.write(", "); }
                    self.emit_pattern(p)?;
                }
                self.write(")");
            }
            Pattern::Struct { path, fields, rest } => {
                self.emit_type_path(path)?;
                self.write(" { ");
                for (i, f) in fields.iter().enumerate() {
                    if i > 0 { self.write(", "); }
                    self.write(&f.name.name);
                    if let Some(ref pat) = f.pattern {
                        self.write(": ");
                        self.emit_pattern(pat)?;
                    }
                }
                if *rest {
                    if !fields.is_empty() { self.write(", "); }
                    self.write("..");
                }
                self.write(" }");
            }
            Pattern::Or(patterns) => {
                for (i, p) in patterns.iter().enumerate() {
                    if i > 0 { self.write(" | "); }
                    self.emit_pattern(p)?;
                }
            }
            Pattern::Slice(patterns) => {
                self.write("[");
                for (i, p) in patterns.iter().enumerate() {
                    if i > 0 { self.write(", "); }
                    self.emit_pattern(p)?;
                }
                self.write("]");
            }
            Pattern::Ref { mutable, pattern } => {
                self.write("&");
                if *mutable { self.write("mut "); }
                self.emit_pattern(pattern)?;
            }
            Pattern::RefBinding { mutable, name, .. } => {
                // ref ident or ref mut ident (binding by reference)
                self.write("ref ");
                if *mutable { self.write("mut "); }
                self.write(&name.name);
            }
            Pattern::Range { start, end, inclusive } => {
                if let Some(s) = start { self.emit_pattern(s)?; }
                self.write(if *inclusive { "..=" } else { ".." });
                if let Some(e) = end { self.emit_pattern(e)?; }
            }
            Pattern::Rest => {
                self.write("..");
            }
        }
        Ok(())
    }

    fn emit_literal(&mut self, lit: &Literal) -> RustCodegenResult<()> {
        match lit {
            Literal::Int { value, suffix, .. } => {
                self.write(value);
                if let Some(s) = suffix { self.write(s); }
            }
            Literal::Float { value, suffix } => {
                self.write(value);
                if let Some(s) = suffix { self.write(s); }
            }
            Literal::String(s) => write!(self.output, "\"{}\"", escape_string(s)).unwrap(),
            Literal::Char(c) => write!(self.output, "'{}'", escape_char(*c)).unwrap(),
            Literal::Bool(b) => write!(self.output, "{}", b).unwrap(),
            Literal::Null => self.write("None"),
            _ => self.write("/* TODO: literal */"),
        }
        Ok(())
    }

    fn emit_binop(&mut self, op: &BinOp) {
        let s = match op {
            BinOp::Add => "+", BinOp::Sub => "-", BinOp::Mul => "*", BinOp::Div => "/",
            BinOp::Rem => "%", BinOp::And => "&&", BinOp::Or => "||",
            BinOp::BitAnd => "&", BinOp::BitOr => "|", BinOp::BitXor => "^",
            BinOp::Shl => "<<", BinOp::Shr => ">>",
            BinOp::Eq => "==", BinOp::Ne => "!=",
            BinOp::Lt => "<", BinOp::Le => "<=", BinOp::Gt => ">", BinOp::Ge => ">=",
            BinOp::Pow => "pow", BinOp::Concat => "+",
            BinOp::MatMul | BinOp::Hadamard | BinOp::TensorProd | BinOp::Convolve => "/* TODO: matrix op */",
        };
        self.write(s);
    }

    fn emit_unop(&mut self, op: &UnaryOp) {
        match op {
            UnaryOp::Neg => self.write("-"),
            UnaryOp::Not => self.write("!"),
            UnaryOp::Deref => self.write("*"),
            UnaryOp::Ref => self.write("&"),
            UnaryOp::RefMut => self.write("&mut "),
        }
    }

    /// Detect if an expression looks like a pipe operation misidentified as BitOr RHS.
    /// Returns the method chain string if detected, None otherwise.
    fn detect_pipe_method(expr: &Expr) -> Option<String> {
        // Check for bare identifier that matches iterator methods
        if let Expr::Path(path) = expr {
            if path.segments.len() == 1 {
                let name = path.segments[0].ident.name.as_str();
                // Common iterator morphemes/methods that might be misidentified
                let method = match name {
                    "sorted" | "sort" | "σ" => Some(".sorted()"),
                    "iter" => Some(".iter()"),
                    "into_iter" => Some(".into_iter()"),
                    "rev" | "reverse" => Some(".rev()"),
                    "collect" => Some(".collect::<Vec<_>>()"),
                    "enumerate" => Some(".enumerate()"),
                    "flatten" => Some(".flatten()"),
                    "unique" | "distinct" | "δ" => Some(".collect::<std::collections::HashSet<_>>().into_iter()"),
                    "sum" | "Σ" => Some(".sum::<_>()"),
                    "product" | "prod" | "Π" => Some(".product::<_>()"),
                    "first" | "α" => Some(".next()"),
                    "last" | "ω" => Some(".last()"),
                    "count" => Some(".count()"),
                    "any" => Some(".any(|x| x)"),
                    "all" => Some(".all(|x| x)"),
                    "min" => Some(".min()"),
                    "max" => Some(".max()"),
                    "cloned" => Some(".cloned()"),
                    "copied" => Some(".copied()"),
                    _ => None,
                };
                return method.map(|s| s.to_string());
            }
        }

        // Check for function call like `join(",")` which should be `.join(",")`
        if let Expr::Call { func, args: _ } = expr {
            if let Expr::Path(path) = func.as_ref() {
                if path.segments.len() == 1 {
                    let name = path.segments[0].ident.name.as_str();
                    // Known pipe functions that take args
                    if matches!(name, "join" | "take" | "skip" | "nth" | "chunks" | "filter" | "map" | "fold" | "reduce") {
                        // Return None - we need to handle this specially with args
                        // This will be handled by emit_pipe_call below
                        return None; // Let it fall through to special handling
                    }
                }
            }
        }

        // Check for method call chain like `sorted.iter()` which should be `.sorted().iter()`
        if let Expr::Incorporation { segments } = expr {
            if !segments.is_empty() {
                let first_name = segments[0].name.name.as_str();
                // Check if first segment is a known morpheme
                if let Some(base_method) = match first_name {
                    "sorted" | "sort" | "σ" => Some(".sorted()"),
                    "iter" => Some(".iter()"),
                    "rev" | "reverse" => Some(".rev()"),
                    "enumerate" => Some(".enumerate()"),
                    "flatten" => Some(".flatten()"),
                    "cloned" => Some(".cloned()"),
                    "copied" => Some(".copied()"),
                    _ => None,
                } {
                    // Build the full method chain
                    let mut chain = base_method.to_string();
                    for seg in segments.iter().skip(1) {
                        chain.push('.');
                        chain.push_str(&seg.name.name);
                        if let Some(ref args) = seg.args {
                            chain.push('(');
                            // We can't easily emit complex args here, so just note it needs args
                            if !args.is_empty() {
                                chain.push_str("/* args */");
                            }
                            chain.push(')');
                        }
                    }
                    return Some(chain);
                }
            }
        }

        None
    }

    /// Get precedence level for a binary operator (higher = binds tighter)
    fn binop_precedence(op: &BinOp) -> u8 {
        match op {
            // Multiplicative (highest)
            BinOp::Mul | BinOp::Div | BinOp::Rem | BinOp::Pow => 11,
            // Additive
            BinOp::Add | BinOp::Sub | BinOp::Concat => 10,
            // Shift
            BinOp::Shl | BinOp::Shr => 9,
            // Bitwise AND
            BinOp::BitAnd => 8,
            // Bitwise XOR
            BinOp::BitXor => 7,
            // Bitwise OR
            BinOp::BitOr => 6,
            // Comparison
            BinOp::Eq | BinOp::Ne | BinOp::Lt | BinOp::Le | BinOp::Gt | BinOp::Ge => 5,
            // Logical AND
            BinOp::And => 4,
            // Logical OR
            BinOp::Or => 3,
            // Matrix/tensor ops (treat same as multiplication for safety)
            BinOp::MatMul | BinOp::Hadamard | BinOp::TensorProd | BinOp::Convolve => 11,
        }
    }

    /// Check if a child expression needs parentheses when used as operand of parent_op
    fn needs_parens_for_binop(child: &Expr, parent_op: &BinOp, is_left: bool) -> bool {
        match child {
            Expr::Binary { op: child_op, .. } => {
                let parent_prec = Self::binop_precedence(parent_op);
                let child_prec = Self::binop_precedence(child_op);

                // Need parens if child has lower precedence
                if child_prec < parent_prec {
                    return true;
                }

                // For same precedence on right side, need parens for non-associative ops
                // and for left-associative ops when child is on right
                if child_prec == parent_prec && !is_left {
                    // Comparison ops are non-associative in Rust
                    if matches!(parent_op, BinOp::Eq | BinOp::Ne | BinOp::Lt | BinOp::Le | BinOp::Gt | BinOp::Ge) {
                        return true;
                    }
                }

                false
            }
            // Casts have higher precedence than most binary ops, but for clarity
            // we parenthesize casts that are operands of bitwise/shift ops
            Expr::Cast { .. } => {
                matches!(parent_op, BinOp::BitAnd | BinOp::BitOr | BinOp::BitXor | BinOp::Shl | BinOp::Shr)
            }
            _ => false,
        }
    }

    /// Clean up struct literal tokens from Sigil certainty syntax.
    /// Converts `{ field : value !, other : x }` to `{ field: value, other: x }`
    fn clean_struct_tokens(tokens: &str) -> String {
        let mut result = String::new();
        let mut chars = tokens.chars().peekable();

        while let Some(c) = chars.next() {
            match c {
                // Remove spaces around colons in field: value
                ' ' if result.ends_with(':') => {
                    // Skip space after colon
                    continue;
                }
                ':' => {
                    // Remove trailing space before colon if present
                    if result.ends_with(' ') {
                        result.pop();
                    }
                    result.push(':');
                    // Skip space after colon if present
                    if chars.peek() == Some(&' ') {
                        chars.next();
                    }
                }
                // Remove evidentiality markers (! ~ ?) after values, before comma or }
                '!' | '~' | '?' => {
                    // Check if next non-space char is , or } or end
                    let mut peek_iter = chars.clone();
                    let mut next_meaningful = None;
                    while let Some(&pc) = peek_iter.peek() {
                        if pc == ' ' {
                            peek_iter.next();
                        } else {
                            next_meaningful = Some(pc);
                            break;
                        }
                    }
                    // If followed by , or } or nothing, this is an evidentiality marker - skip it
                    match next_meaningful {
                        Some(',') | Some('}') | None => continue,
                        _ => result.push(c),
                    }
                }
                _ => result.push(c),
            }
        }
        result
    }
}

impl Default for RustCompiler {
    fn default() -> Self { Self::new() }
}

fn escape_string(s: &str) -> String {
    let mut result = String::new();
    for c in s.chars() {
        match c {
            '\n' => result.push_str("\\n"),
            '\r' => result.push_str("\\r"),
            '\t' => result.push_str("\\t"),
            '\\' => result.push_str("\\\\"),
            '"' => result.push_str("\\\""),
            c => result.push(c),
        }
    }
    result
}

fn escape_char(c: char) -> String {
    match c {
        '\n' => "\\n".to_string(),
        '\r' => "\\r".to_string(),
        '\t' => "\\t".to_string(),
        '\\' => "\\\\".to_string(),
        '\'' => "\\'".to_string(),
        c => c.to_string(),
    }
}

